# RFC 7801, раздел с контрольным примером.
RFC_KEY = bytes.fromhex(
    "8899AABBCCDDEEFF0011223344556677FEDCBA98765432100123456789ABCDEF"
)
RFC_PLAIN = bytes.fromhex("1122334455667700FFEEDDCCBBAA9988")
RFC_CIPHER = bytes.fromhex("7F679D90BEBC24305A468D42B9D4EDCD")

_PI_INV = bytearray(256)
for _index, _value in enumerate(_PI):
    _PI_INV[_value] = _index
_PI_INV = bytes(_PI_INV)


def _mul(left: int, right: int) -> int:
    """Умножение в GF(2^8) с полиномом x^8 + x^7 + x^6 + x + 1."""

    result = 0
    while right:
        if right & 1:
            result ^= left
        left = ((left << 1) & 0xFF) ^ (0xC3 if left & 0x80 else 0)
        right >>= 1
    return result


def _xor(left: bytes, right: bytes) -> bytes:
    return bytes(a ^ b for a, b in zip(left, right, strict=True))


def _s(block: bytes) -> bytes:
    return bytes(_PI[byte] for byte in block)


def _s_inv(block: bytes) -> bytes:
    return bytes(_PI_INV[byte] for byte in block)


def _l(block: bytes) -> bytes:
    state = bytearray(block)
    for _ in range(16):
        value = state[15]
        for index in range(14, -1, -1):
            state[index + 1] = state[index]
            value ^= _mul(state[index], _LVEC[index])
        state[0] = value
    return bytes(state)


def _l_inv(block: bytes) -> bytes:
    state = bytearray(block)
    for _ in range(16):
        value = state[0]
        for index in range(15):
            state[index] = state[index + 1]
            value ^= _mul(state[index], _LVEC[index])
        state[15] = value
    return bytes(state)


def _round_keys(key: bytes) -> list[bytes]:
    if len(key) != 32:
        raise ValueError("Кузнечик принимает ключ ровно 32 байта")
    left = key[:16]
    right = key[16:]
    keys = [left, right]
    for index in range(1, 33):
        constant = bytearray(16)
        constant[15] = index
        mixed = _l(bytes(constant))
        updated = _l(_s(_xor(left, mixed)))
        updated = _xor(updated, right)
        right = left
        left = updated
        if index % 8 == 0:
            keys.append(left)
            keys.append(right)
    return keys


def encrypt_block(key: bytes, block: bytes) -> bytes:
    if len(block) != 16:
        raise ValueError("блок Кузнечика — 16 байт")
    keys = _round_keys(key)
    state = block
    for round_key in keys[:9]:
        state = _l(_s(_xor(state, round_key)))
    return _xor(state, keys[9])


def decrypt_block(key: bytes, block: bytes) -> bytes:
    if len(block) != 16:
        raise ValueError("блок Кузнечика — 16 байт")
    keys = _round_keys(key)
    state = _xor(block, keys[9])
    for round_key in reversed(keys[:9]):
        state = _xor(_s_inv(_l_inv(state)), round_key)
    return state


def rfc_vector_matches() -> bool:
    return (
        encrypt_block(RFC_KEY, RFC_PLAIN) == RFC_CIPHER
        and decrypt_block(RFC_KEY, RFC_CIPHER) == RFC_PLAIN
    )
